  function get(dexNo) {
    var row = E[dexNo];
    if (!row) {
      // 152–386：名称由图鉴清单兜底，进化链仍只走 001–151 原表（不动既有进化逻辑）
      return (APP.dexData && APP.dexData.infoOf) ? APP.dexData.infoOf(dexNo) : null;
    }
    var next = [];
    for (var i = 0; i < row[2].length; i++) {
      var n = row[2][i];
      next.push({ dexNo: n[0], name: n[1], kind: n[2], need: n[3] });
    }
    return { dexNo: dexNo, name: row[0], stage: row[1], next: next };
  }

  function hasNext(dexNo) {
    var row = E[dexNo];
    return !!(row && row[2] && row[2].length);
  }

  // 是否「进化链末端」：由关都内某只进化而来，且自己没有再进化。
  // 完全不进化的宝可梦（卡比兽、肯泰罗等）不算末端，不弹「已是最终形态」提醒。
  function isFinalForm(dexNo) {
    var row = E[dexNo];
    if (!row) return false;
    return !!PARENT[dexNo] && (!row[2] || !row[2].length);
  }

  // 当前等级是否满足某个等级型进化；返回下一阶段或 null
  function levelNext(dexNo, level) {
    var row = E[dexNo];
    if (!row) return null;
    var lv = Number(level) || 0;
    for (var i = 0; i < row[2].length; i++) {
      var n = row[2][i];
      if (n[2] === 'level' && lv >= n[3]) {
        return { dexNo: n[0], name: n[1], kind: n[2], need: n[3] };
      }
    }
    return null;
  }

  // 该编号下一次等级进化需要的等级（只用于提示），没有则 0
  function levelNeed(dexNo) {
    var row = E[dexNo];
    if (!row) return 0;
    for (var i = 0; i < row[2].length; i++) {
      if (row[2][i][2] === 'level') return row[2][i][3];
    }
    return 0;
  }

  // 未启用的进化方式（石头 / 交换 / 特殊条件），供以后评估时查阅
  function pendingNext(dexNo) {
    var row = E[dexNo];
    if (!row) return [];
    var out = [];
    for (var i = 0; i < row[2].length; i++) {
      var n = row[2][i];
      if (n[2] !== 'level') {
        out.push({
          dexNo: n[0],
          name: n[1],
          kind: n[2],
          need: n[3],
          itemName: n[2] === 'item' ? (ITEM_CN[n[3]] || n[3]) : ''
        });
      }
    }
    return out;
  }

  // 捕捉限制：只有基础形态可直接捕捉；已有进化形态只能靠升级获得
  function catchAllowed(dexNo) {
    var row = E[dexNo];
    if (!row) return false;
    return row[1] === 0;
  }

  // ===== 反向查询（供「宝可梦调试 → 重置照顾对象」使用）=====
  // 复用上面的 PARENT 表：进化在关都内是一棵树，每个形态最多一个上一阶段，
  // 沿 PARENT 向上走就能回到基础形态。跨世代前置（如卡比兽 ← 小卡比兽 #446）不在表内，
  // 这类宝可梦会被当作自己的基础形态。

  // 沿进化链向上找到基础形态；本身已是基础形态则返回自身
  function rootOf(dexNo) {
    var n = Number(dexNo);
    if (!E[n]) return null;
    var guard = 0;
    while (PARENT[n] && guard < 10) {
      n = PARENT[n];
      guard++;
    }
    return { dexNo: n, name: E[n][0], stage: E[n][1] };
  }

  // 该形态走过的整条链路（自身 → 基础形态）。重置时用它清理图鉴记录。
  function chainOf(dexNo) {
    var n = Number(dexNo);
    var out = [];
    if (!E[n]) return out;
    var guard = 0;
    out.push(n);
    while (PARENT[n] && guard < 10) {
      n = PARENT[n];
      out.push(n);
      guard++;
    }
    return out;
  }

